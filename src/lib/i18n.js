export function makeT(lang) {
  const l = LANGS.includes(lang) ? lang : 'th'
  return (key, vars) => {
    const entry = dict[key]
    let text = entry ? (entry[l] ?? entry.th) : key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, v)
    }
    return text
  }
}
